/**
 * Secrets directory as seen by the api-gateway (10.4, docs/setup.md
 * "Automatic secrets").
 *
 *  - The container entrypoint creates/loads <dir>/coremail.env
 *    (infra/docker/init-secrets.mjs) and exports two markers this module reads:
 *    COREMAIL_SECRETS_FILE_IN_USE and COREMAIL_SECRETS_GENERATED. The file
 *    itself belongs to root; the setup wizard's download (10.4.2) reads the
 *    copy the entrypoint stages for it (see "Secrets download" below).
 *  - While the initial setup is pending, the one-time setup token is written
 *    to <dir>/setup-token (0600, atomic) — the log then names the file instead
 *    of printing the token. The file is deleted when the setup completes.
 *
 * <dir> = COREMAIL_SECRETS_DIR (default /secrets). Host-relative hints for
 * messages use COREMAIL_SECRETS_HOST_PATH (default ./secrets — the bind mount
 * of the Compose files).
 */
import { randomBytes } from 'node:crypto';
import { promises as fs, constants } from 'node:fs';
import type { FileHandle } from 'node:fs/promises';
import { isAbsolute, join, resolve } from 'node:path';

export const SETUP_TOKEN_FILE = 'setup-token';
export const SECRETS_FILE = 'coremail.env';

type Env = NodeJS.ProcessEnv;

export function secretsDir(env: Env = process.env): string {
  const d = (env['COREMAIL_SECRETS_DIR'] ?? '').trim();
  return d || '/secrets';
}

/** Path of the secrets directory as the operator sees it on the host. */
export function secretsHostPath(env: Env = process.env): string {
  const p = (env['COREMAIL_SECRETS_HOST_PATH'] ?? '').trim().replace(/\/+$/, '');
  return p || './secrets';
}

export interface SecretsStatus {
  /** Host-relative path of the secrets file when the entrypoint loaded it, else null. */
  secretsFile: string | null;
  /** true when that file was (at least partly) generated by CoreMail. */
  secretsGenerated: boolean;
}

/** For GET /api/v1/setup/status — a path hint and a boolean, never a value. */
export function secretsStatus(env: Env = process.env): SecretsStatus {
  const inUse = env['COREMAIL_SECRETS_FILE_IN_USE'] === 'true';
  return {
    secretsFile: inUse ? `${secretsHostPath(env)}/${SECRETS_FILE}` : null,
    secretsGenerated: inUse && env['COREMAIL_SECRETS_GENERATED'] === 'true',
  };
}

/** true when the secrets directory exists as a real directory (no symlink). */
async function usableDir(dir: string): Promise<boolean> {
  try {
    const st = await fs.lstat(dir);
    return st.isDirectory();
  } catch {
    return false;
  }
}

/**
 * Writes the token to <dir>/setup-token (0600): exclusive temp file, fsync,
 * rename — a symlink planted at either name is never followed. Returns the
 * container path, or null when there is no secrets directory or it is not
 * writable (the caller then logs the token as before).
 */
export async function writeSetupTokenFile(token: string, env: Env = process.env): Promise<string | null> {
  const dir = secretsDir(env);
  if (!(await usableDir(dir))) return null;
  const target = join(dir, SETUP_TOKEN_FILE);
  const tmp = join(dir, `.${SETUP_TOKEN_FILE}.tmp-${randomBytes(6).toString('hex')}`);
  const flags = constants.O_WRONLY | constants.O_CREAT | constants.O_EXCL | (constants.O_NOFOLLOW ?? 0);
  let handle: FileHandle | null = null;
  try {
    handle = await fs.open(tmp, flags, 0o600);
    await handle.chmod(0o600).catch(() => undefined);
    await handle.writeFile(`${token}\n`, 'utf8');
    await handle.sync();
    await handle.close();
    handle = null;
    await fs.rename(tmp, target);
    return target;
  } catch {
    if (handle) await handle.close().catch(() => undefined);
    await fs.unlink(tmp).catch(() => undefined);
    return null;
  }
}

/** Deletes <dir>/setup-token (no error when it does not exist). Returns true when a file was removed. */
export async function removeSetupTokenFile(env: Env = process.env): Promise<boolean> {
  const dir = secretsDir(env);
  if (!(await usableDir(dir))) return false;
  try {
    await fs.unlink(join(dir, SETUP_TOKEN_FILE));
    return true;
  } catch {
    return false;
  }
}

// ── Secrets download of the setup wizard (10.4.2) ────────────────────────────
//
// GET /api/v1/setup/secrets-download hands the admin the secrets file while
// the wizard runs. The file in <dir> belongs to root (0600) and is never made
// readable for user node: the entrypoint stages a byte-identical copy owned by
// node in the container's /tmp and names it in COREMAIL_SECRETS_DOWNLOAD_FILE
// (only when the secrets were generated). The api-gateway deletes that copy as
// soon as the download window is closed. Without the variable (development,
// tests, a container running as the file's owner) <dir>/coremail.env is read
// directly — and never deleted.

/** The download is possible at most this long after the setup was completed. */
export const SECRETS_DOWNLOAD_WINDOW_MS = 24 * 60 * 60 * 1000;

/** Largest file served (the generator writes a few hundred bytes). */
const MAX_DOWNLOAD_BYTES = 64 * 1024;

export interface SetupWindowState {
  setupCompletedAt?: Date | null;
  setupWizardFinishedAt?: Date | null;
}

/**
 * Open only after the setup was completed, while the wizard has not reached
 * its summary, and at most 24 h after the completion.
 */
export function secretsDownloadWindowOpen(s: SetupWindowState | null | undefined, now: Date = new Date()): boolean {
  const done = s?.setupCompletedAt;
  if (!(done instanceof Date) || Number.isNaN(done.getTime())) return false;
  if (s?.setupWizardFinishedAt) return false;
  const age = now.getTime() - done.getTime();
  return age >= 0 && age <= SECRETS_DOWNLOAD_WINDOW_MS;
}

/** The staged copy named by the entrypoint, or null (then the real file is read). */
function stagedCopyPath(env: Env): string | null {
  const p = (env['COREMAIL_SECRETS_DOWNLOAD_FILE'] ?? '').trim();
  if (!p || !isAbsolute(p)) return null;
  // never treat the real secrets file as a disposable copy
  if (resolve(p) === resolve(secretsDir(env), SECRETS_FILE)) return null;
  return p;
}

/** The file the download serves. */
export function secretsDownloadPath(env: Env = process.env): string {
  return stagedCopyPath(env) ?? join(secretsDir(env), SECRETS_FILE);
}

/**
 * Reads the file for the download: no symlink, a regular file with one link,
 * at most 64 KiB. null when it is absent or unreadable (the route answers 404).
 */
export async function readSecretsForDownload(env: Env = process.env): Promise<Buffer | null> {
  let handle: FileHandle | null = null;
  try {
    handle = await fs.open(secretsDownloadPath(env), constants.O_RDONLY | (constants.O_NOFOLLOW ?? 0));
    const st = await handle.stat();
    if (!st.isFile() || st.nlink > 1 || st.size > MAX_DOWNLOAD_BYTES) return null;
    return await handle.readFile();
  } catch {
    return null;
  } finally {
    if (handle) await handle.close().catch(() => undefined);
  }
}

/** Deletes the staged copy (never the real secrets file). Returns true when a file was removed. */
export async function removeStagedSecretsCopy(env: Env = process.env): Promise<boolean> {
  const p = stagedCopyPath(env);
  if (!p) return false;
  try {
    await fs.unlink(p);
    return true;
  } catch {
    return false;
  }
}

/** `coremail-secrets-<host>-<YYYY-MM-DD>.env` (host reduced to safe characters). */
export function secretsDownloadFilename(host: string | null | undefined, now: Date = new Date()): string {
  const h = (host ?? '').trim().toLowerCase().replace(/[^a-z0-9.-]+/g, '-').replace(/^[.-]+|[.-]+$/g, '').slice(0, 100);
  return `coremail-secrets-${h || 'server'}-${now.toISOString().slice(0, 10)}.env`;
}

/** Schema defaults / loopback names — not an address a browser elsewhere can use. */
const PLACEHOLDER_HOSTS = new Set(['', 'mail.local', 'mail.localhost', 'localhost', 'localhost.localdomain']);

/**
 * URL of the setup wizard as it answers on a FRESH installation: plain HTTP on
 * the published HTTP port (the integrated HTTPS proxy starts only once a
 * certificate exists). Port: COREMAIL_PUBLIC_HTTP_PORT (the Compose files set
 * the host port they publish; default 3000). Host: the public host name when
 * one is configured, else the placeholder `<server>`.
 */
export function setupUrlHint(env: Env = process.env, publicHostname?: string | null): string {
  const rawPort = (env['COREMAIL_PUBLIC_HTTP_PORT'] ?? '').trim();
  const port = /^\d{1,5}$/.test(rawPort) && Number(rawPort) > 0 && Number(rawPort) < 65536 ? String(Number(rawPort)) : '3000';
  const h = (publicHostname ?? '').trim().toLowerCase().replace(/\.$/, '');
  const host = !PLACEHOLDER_HOSTS.has(h) && /^[a-z0-9]([a-z0-9-]*[a-z0-9])?(\.[a-z0-9]([a-z0-9-]*[a-z0-9])?)*$/.test(h) ? h : '<server>';
  return `http://${host}${port === '80' ? '' : `:${port}`}/setup`;
}

/** Framed log message pointing at the token file (the token itself is not logged). */
export function setupTokenFileBanner(env: Env = process.env, publicHostname?: string | null): string {
  const file = `${secretsHostPath(env)}/${SETUP_TOKEN_FILE}`;
  return (
    `\n════════════════════════════════════════════════════════════════════\n` +
    `  CoreMail setup: open ${setupUrlHint(env, publicHostname)} — token in ${file}\n` +
    `  (one-time setup token; a new one is written on every restart\n` +
    `  until the setup is done, then the file is deleted)\n` +
    `════════════════════════════════════════════════════════════════════`
  );
}
